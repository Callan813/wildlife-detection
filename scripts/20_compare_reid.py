"""Phase 3 extra, step 5: did adding LeopardID102 leopards to training help?

    python scripts/20_compare_reid.py --config configs/phase3.yaml

Compares re-ID models trained by 14_train_reid.py on the same Leopard ID 2022 test
leopards (107, never trained on). Two sources of noise matter here:

- Which leopards happen to be in the test set. With ~100 leopards a top-1 number moves
  by about ±5 points. Since every model is scored on the same leopards, the
  difference between two models is checked with a paired bootstrap: resample the test
  leopards with replacement, recompute the difference, and take the 2.5-97.5%
  interval. If the interval excludes zero, the gap is bigger than test-set luck.
- Training randomness (seed: data order, augmentation, head init). The bootstrap can't
  see that, so the same setup is trained with two seeds and the seed-to-seed gap
  is shown next to the gap from adding data.

Test embeddings are cached next to each checkpoint (test_embeddings.npz). Writes
reports/phase3/reid_compare.md.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from ghats.config import load_config
from ghats.reid import retrieval_metrics

MODELS = {
    "Leopard ID 2022 only, seed 0": "outputs/phase3/reid",
    "Leopard ID 2022 only, seed 1": "outputs/phase3/reid_s1",
    "+ LeopardID102, seed 0": "outputs/phase3/reid_lp102_s0",
    "+ LeopardID102, seed 1": "outputs/phase3/reid_lp102_s1",
}
COMPARISONS = [
    # (label, model A, model B): B minus A
    ("Seed only (no new data)", "Leopard ID 2022 only, seed 0", "Leopard ID 2022 only, seed 1"),
    ("Add LeopardID102, seed 0", "Leopard ID 2022 only, seed 0", "+ LeopardID102, seed 0"),
    ("Add LeopardID102, seed 1", "Leopard ID 2022 only, seed 1", "+ LeopardID102, seed 1"),
]


def test_embeddings(model_dir: Path, paths: list[Path], cfg: dict) -> np.ndarray:
    cache = model_dir / "test_embeddings.npz"
    if cache.exists() and len(np.load(cache)["x"]) == len(paths):
        return np.load(cache)["x"]
    import torch

    from ghats.reid_model import embed, eval_loader, load_trained

    device = "cuda" if torch.cuda.is_available() else "cpu"
    model = load_trained(model_dir / "best.pt", device)
    x = embed(model, eval_loader(paths, cfg, model), device)
    np.savez(cache, x=x)
    return x


def per_leopard(emb: np.ndarray, crops: pd.DataFrame, ks) -> pd.DataFrame:
    """Top-k hit rate for each test leopard (rows) under the Phase 3 rules."""
    rows = {}
    for name in crops["name"].unique():
        m = retrieval_metrics(
            emb, crops["name"], crops["encounter"], crops["viewpoint"], ks, queries=crops["name"] == name
        )
        if m["queries"]:
            rows[name] = {f"top{k}": m[f"top{k}"] for k in ks}
    return pd.DataFrame.from_dict(rows, orient="index")


def paired_bootstrap(a: pd.Series, b: pd.Series, n: int = 5000, seed: int = 0) -> tuple[float, float, float]:
    """Mean of b - a over leopards, with a 95% interval from resampling leopards."""
    d = (b - a).to_numpy()
    rng = np.random.default_rng(seed)
    means = d[rng.integers(0, len(d), size=(n, len(d)))].mean(axis=1)
    return float(d.mean()), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/phase3.yaml")
    ap.add_argument("--reports", default="reports/phase3")
    args = ap.parse_args()

    cfg = load_config(args.config)
    ks = cfg["reid"]["ks"]
    crop_dir = Path(cfg["crops"]["out"])
    crops = pd.read_csv(crop_dir / "crops.csv")
    test = crops[crops["split"] == "test"].reset_index(drop=True)
    paths = [crop_dir / "images" / f"{c}.jpg" for c in test["crop_id"]]

    scores, overall = {}, {}
    for label, d in MODELS.items():
        if not (Path(d) / "best.pt").exists():
            print(f"missing {d}/best.pt, skipping {label}")
            continue
        emb = test_embeddings(Path(d), paths, cfg["train"])
        scores[label] = per_leopard(emb, test, ks)
        overall[label] = retrieval_metrics(emb, test["name"], test["encounter"], test["viewpoint"], ks)

    cols = [f"top{k}_per_id" for k in ks] + ["mAP"]
    lines = [
        "# Does adding LeopardID102 leopards to training help?",
        "",
        (
            "Generated by `scripts/20_compare_reid.py`. All models: DINOv2-S + ArcFace, same settings "
            "(configs/phase3.yaml), best epoch by val top-1. Scored on the same "
            f"{test['name'].nunique()} Leopard ID 2022 test leopards, never trained on."
        ),
        "",
        "| Model | " + " | ".join(f"Top-{k}" for k in ks) + " | mAP |",
        "|---|" + "---|" * len(cols),
        *(f"| {lab} | " + " | ".join(f"{m[c]:.1%}" for c in cols) + " |" for lab, m in overall.items()),
        "",
        "## Differences, with 95% intervals from resampling test leopards",
        "",
        "| Comparison | " + " | ".join(f"Top-{k} change" for k in ks) + " |",
        "|---|" + "---|" * len(ks),
    ]
    for label, a, b in COMPARISONS:
        if a not in scores or b not in scores:
            continue
        cells = []
        for k in ks:
            mean, lo, hi = paired_bootstrap(scores[a][f"top{k}"], scores[b][f"top{k}"])
            cells.append(f"{mean * 100:+.1f} ({lo * 100:+.1f} to {hi * 100:+.1f})")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += [
        "",
        (
            "Points, per-leopard average. The interval covers test-set luck only; the seed-only row shows "
            "how much a change of random seed alone moves things."
        ),
    ]
    Path(args.reports, "reid_compare.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
